using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace MC10.Core
{
    public enum LineKind { Header, Blank, Comment, Label, Code, Data }

    public sealed class ListingLine
    {
        public ushort Address { get; }
        public string Text { get; }
        public LineKind Kind { get; }
        public ListingLine(ushort address, LineKind kind, string text) { Address = address; Kind = kind; Text = text; }
        public override string ToString() => Text;
    }

    /// <summary>Turns an <see cref="Analysis"/> into an annotated assembly listing.</summary>
    public static class Listing
    {
        /// <param name="userLabels">Hand-made or loaded names; they replace the automatic label at that address.</param>
        /// <param name="describe">Optional "routine+offset" naming for the addresses that call or reference a label.</param>
        public static List<ListingLine> Build(Analysis an, Func<ushort, string> symbol, Func<ushort, string> immSymbol,
                                              string title, IReadOnlyDictionary<ushort, string> userLabels = null,
                                              Func<ushort, string> describe = null)
        {
            var lines = new List<ListingLine>();
            ushort first = (ushort)an.Base;
            lines.Add(new ListingLine(first, LineKind.Header, "; " + title));
            lines.Add(new ListingLine(first, LineKind.Header,
                $"; ROM ${an.Base:X4}-${an.Base + an.Size - 1:X4}   {an.InstructionCount} instructions, " +
                $"{an.CodeByteCount} code bytes, {an.Size - an.CodeByteCount} data bytes, {an.Subroutines.Count} subroutines"));
            lines.Add(new ListingLine(first, LineKind.Header,
                "; Generated by static analysis from the interrupt vectors. Code reached only through indirect"));
            lines.Add(new ListingLine(first, LineKind.Header,
                "; jumps or RAM vectors may appear as data. Names are automatic (sub_/loc_/data_/fn_/tbl_)."));

            Func<int, byte> read = a => an.Contains(a) ? an.At(a) : (byte)0xFF;
            int end = an.Base + an.Size;
            int addr = an.Base;
            while (addr < end)
            {
                ushort ad = (ushort)addr;
                AddLabel(an, lines, ad, userLabels, describe);

                if (an.CodeStart[addr - an.Base])
                {
                    string dis = Disassembler.Disassemble(a => read(a), ad, out int len, symbol, immSymbol);
                    string hex = Disassembler.HexBytes(a => read(a), ad, len);
                    lines.Add(new ListingLine(ad, LineKind.Code, $"  {ad:X4}  {hex,-9} {dis}"));
                    addr += len;
                    continue;
                }

                if (addr >= 0xFFF0 && addr + 1 < end && (addr & 1) == 0)
                {
                    ushort w = (ushort)((read(addr) << 8) | read(addr + 1));
                    string name = an.VectorNames.TryGetValue(ad, out var vn) ? vn : "vector";
                    string tgt = symbol(w) ?? "$" + w.ToString("X4");
                    lines.Add(new ListingLine(ad, LineKind.Data, $"  {ad:X4}  {read(addr):X2} {read(addr + 1):X2}     FDB   {tgt,-10} ; {name}"));
                    addr += 2;
                    continue;
                }

                // Pointer table: one word per line with its target label.
                if (an.PointerTable[addr - an.Base] && addr + 1 < end)
                {
                    ushort w = (ushort)((read(addr) << 8) | read(addr + 1));
                    string tgt = symbol(w) ?? "$" + w.ToString("X4");
                    lines.Add(new ListingLine(ad, LineKind.Data, $"  {ad:X4}  {read(addr):X2} {read(addr + 1):X2}     FDB   {tgt}"));
                    addr += 2;
                    continue;
                }

                // Collapse long runs of one byte (fill).
                int run = 1;
                while (addr + run < end && read(addr + run) == read(addr) && !an.CodeStart[addr + run - an.Base]
                       && !an.Labels.ContainsKey((ushort)(addr + run)) && !an.PointerTable[addr + run - an.Base]
                       && addr + run < 0xFFF0) run++;
                if (run >= 16)
                {
                    lines.Add(new ListingLine(ad, LineKind.Data, $"  {ad:X4}  {read(addr):X2} ...    FILL  ${read(addr):X2} x {run} bytes (to ${addr + run - 1:X4})"));
                    addr += run;
                    continue;
                }

                int j = addr;
                var sb = new StringBuilder();
                var ascii = new StringBuilder();
                while (j < end && j - addr < 8 && j < 0xFFF0 && (j == addr ||
                       (!an.CodeStart[j - an.Base] && !an.Labels.ContainsKey((ushort)j) && !an.PointerTable[j - an.Base])))
                {
                    if (j > addr) sb.Append(' ');
                    sb.Append(read(j).ToString("X2"));
                    byte b = read(j);
                    ascii.Append(b >= 0x20 && b < 0x7F ? (char)b : '.');
                    j++;
                }
                lines.Add(new ListingLine(ad, LineKind.Data, $"  {ad:X4}  {sb,-23} FCB   ; {ascii}"));
                addr = j;
            }
            return lines;
        }

        static void AddLabel(Analysis an, List<ListingLine> lines, ushort ad,
                             IReadOnlyDictionary<ushort, string> user, Func<ushort, string> describe)
        {
            string name = null;
            bool hasUser = user != null && user.TryGetValue(ad, out name);
            if (!hasUser && !an.Labels.TryGetValue(ad, out name)) return;
            bool namedRoutine = hasUser && !name.StartsWith("loc_") && !name.StartsWith("data_");
            bool big = an.Subroutines.Contains(ad) || name == "reset" || name.EndsWith("_isr") || name.StartsWith("tbl_")
                       || name.StartsWith("fn_") || namedRoutine;
            if (big)
            {
                lines.Add(new ListingLine(ad, LineKind.Blank, ""));
                lines.Add(new ListingLine(ad, LineKind.Comment, "; " + new string('=', 60)));
                string how = Describe(an, ad, describe);
                if (how.Length > 0) lines.Add(new ListingLine(ad, LineKind.Comment, "; " + how));
            }
            string tail = !big && an.Refs.TryGetValue(ad, out var r) ? "   ; from " + Join(r, 4) : "";
            lines.Add(new ListingLine(ad, LineKind.Label, name + ":" + tail));
        }

        static string Describe(Analysis an, ushort ad, Func<ushort, string> describe)
        {
            var parts = new List<string>();
            if (an.Callers.TryGetValue(ad, out var c)) parts.Add("called from " + Join(c, 8, describe));
            if (an.Refs.TryGetValue(ad, out var r)) parts.Add("referenced from " + Join(r, 6, describe));
            return string.Join("; ", parts);
        }

        static string Join(List<ushort> list, int max, Func<ushort, string> describe = null)
        {
            var s = list.OrderBy(a => a).Take(max).Select(a =>
            {
                string d = describe?.Invoke(a);
                return d == null ? a.ToString("X4") : a.ToString("X4") + " (" + d + ")";
            });
            string text = string.Join(", ", s);
            return list.Count > max ? text + $" (+{list.Count - max} more)" : text;
        }

        public static string ToText(IEnumerable<ListingLine> lines) => string.Join("\n", lines.Select(l => l.Text)) + "\n";
    }
}
